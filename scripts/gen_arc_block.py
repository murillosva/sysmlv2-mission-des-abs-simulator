"""Generate the ``border_sectors`` YAML block, with the ``arc`` polyline of each sector.

Reads the pinned snapshot ``scripts/data/setores_zida_27.json`` (sector method adapted
from Miranda, 2025) and prints the ``border_sectors`` block of
``configs/zida_shield_default.yaml``. Each sector carries ``arc``, the exact polyline of
its border arc as ``(lat, lon, s_km)`` with cumulative arc length, 4 to 22 vertices per
sector.

Deterministic (no random numbers, no timestamp):

* ``start`` and ``end`` are written with 6 decimals, the values of the scenario file;
* the ``arc`` vertices are written verbatim from the JSON (float round trip), so the
  interpolation along the arc follows the source data exactly.

Usage::

    python scripts/gen_arc_block.py                  # to stdout
    python scripts/gen_arc_block.py --out block.yaml
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_DATA = _HERE / "data" / "setores_zida_27.json"


def _fmt_float(x: float) -> str:
    """Float round trip (repr): keeps the precision of the snapshot."""
    return repr(float(x))


def build_block(data_path: Path = _DATA) -> str:
    """Build the text of the ``border_sectors`` block from the snapshot."""
    setores = json.loads(data_path.read_text(encoding="utf-8"))["setores"]

    lines: list[str] = []
    lines.append("# --- Border polygon (sectors 1-27, full BR-CO + BR-PE border) --------")
    lines.append("# N->S: sector 1 = BR-CO-VE tripoint, sector 27 ends at BR-PE-BO tripoint.")
    lines.append("# All 27 endpoints + arc polylines from Natural Earth 50m.")
    lines.append("# Sector method adapted from Miranda (2025). Generated by scripts/gen_arc_block.py.")
    lines.append("# Each sector carries `arc`: the exact polyline (lat, lon, s_km) of its 100-km arc.")
    lines.append("border_sectors:")

    for s in setores:
        idx = int(s["setor"])
        s_lat, s_lon = s["lat_inicial"], s["lon_inicial"]
        e_lat, e_lon = s["lat_final"], s["lon_final"]
        lines.append(f"  - index: {idx}")
        lines.append(f"    start: {{ lat: {s_lat:.6f}, lon: {s_lon:.6f} }}")
        lines.append(f"    end:   {{ lat: {e_lat:.6f}, lon: {e_lon:.6f} }}")
        lines.append("    arc:")
        # arco_lonlat = [[lon, lat], ...] and arco_s_km = [s_km, ...]; `arc` is
        # (lat, lon, s_km), so the order is swapped. Consecutive vertices with the
        # same s_km are dropped (one case in the snapshot: sector 11 repeats a point);
        # this removes a zero-length segment and keeps s_km strictly increasing.
        prev_s: float | None = None
        for (lon, lat), s_km in zip(s["arco_lonlat"], s["arco_s_km"], strict=True):
            if prev_s is not None and s_km == prev_s:
                continue
            prev_s = s_km
            lines.append(
                f"      - [{_fmt_float(lat)}, {_fmt_float(lon)}, {_fmt_float(s_km)}]"
            )

    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate the border_sectors block with arc.")
    ap.add_argument("--data", type=Path, default=_DATA,
                    help="JSON snapshot (default: scripts/data/setores_zida_27.json)")
    ap.add_argument("--out", type=Path, default=None,
                    help="output file (default: stdout)")
    args = ap.parse_args()

    block = build_block(args.data)
    if args.out is None:
        print(block, end="")
    else:
        args.out.write_text(block, encoding="utf-8")
        n = block.count("- index:")
        print(f"Wrote {args.out} ({n} sectors, {len(block)} bytes)")


if __name__ == "__main__":
    main()
